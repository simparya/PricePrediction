import pandas as pd
import numpy as np
import xgboost as xgb
from backtesting import Backtest, Strategy

# ==========================================
# 1. CONFIGURATION & MODEL LOAD
# ==========================================
MODEL_PATH = "nvda_xgboost_model.json"
DATA_PATH = "NVDA_historical_features.csv"

# Exact 9 stationary features used in model_builder.py and main.py
FEATURES = [
    'SMA_10_Ratio', 'SMA_50_Ratio', 'SMA_200_Ratio', 
    'RSI_14', 'ATR_Pct', 'BB_Pct', 'VWAP_Ratio', 'OBV_Z', 'Sentiment_Score'
]

print("Loading model and dataset...")
model = xgb.XGBClassifier()
model.load_model(MODEL_PATH)

# ==========================================
# 2. DEFINE STRATEGY
# ==========================================
class XGBoostBracketStrategy(Strategy):
    tp_atr_mult = 2.0  # +2.0x ATR Take Profit
    sl_atr_mult = 1.0  # -1.0x ATR Stop Loss

    def init(self):
        # Pre-compute model predictions across the entire dataset for fast execution
        X = self.data.df[FEATURES]
        self.predictions = model.predict(X)

    def next(self):
        # Get current bar index and prediction
        i = len(self.data) - 1
        prediction = self.predictions[i]
        price = self.data.Close[-1]

        atr = self.data.df['ATR_14'].iloc[i] if 'ATR_14' in self.data.df.columns else (price * 0.02)
        sma_200 = self.data.df['SMA_200'].iloc[i] if 'SMA_200' in self.data.df.columns else price
        is_bull_market = (price >= sma_200)

        # BUY Signal: Model predicts 1 and price is above 200-day SMA (Bull Regime)
        if prediction == 1 and is_bull_market:
            if not self.position.is_long:
                if self.position.is_short:
                    self.position.close()
                tp_price = price + (self.tp_atr_mult * atr)
                sl_price = max(0.01, price - (self.sl_atr_mult * atr))
                if sl_price >= price:
                    sl_price = price * 0.99
                self.buy(sl=sl_price, tp=tp_price)

        # SELL Signal: Model predicts 0 and price is below 200-day SMA (Bear Regime)
        elif prediction == 0 and not is_bull_market:
            if not self.position.is_short:
                if self.position.is_long:
                    self.position.close()
                tp_price = max(0.01, price - (self.tp_atr_mult * atr))
                if tp_price >= price:
                    tp_price = price * 0.95
                sl_price = price + (self.sl_atr_mult * atr)
                self.sell(sl=sl_price, tp=tp_price)

        # Otherwise: Close position if signal conflicts with secular 200-day trend
        else:
            if self.position:
                self.position.close()

# ==========================================
# 3. RUN BACKTEST
# ==========================================
if __name__ == "__main__":
    # Load dataset generated by model_builder.py
    df = pd.read_csv(DATA_PATH, index_col=0, parse_dates=True)

    # backtesting.py expects capitalized column names
    df.rename(columns={
        'open': 'Open',
        'high': 'High',
        'low': 'Low',
        'close': 'Close',
        'volume': 'Volume'
    }, inplace=True)

    # Ensure dataset is sorted chronologically
    df.sort_index(inplace=True)

    print("Running Backtest...")
    bt = Backtest(
        df, 
        XGBoostBracketStrategy, 
        cash=10000,          # Starting capital ($10,000)
        commission=0.001,    # Estimated slippage / fees (0.1%)
        exclusive_orders=True
    )

    stats = bt.run()
    print("\n" + "="*40)
    print("BACKTEST RESULTS")
    print("="*40)
    print(stats)

    # Generate visual plot (opens in browser)
    bt.plot()